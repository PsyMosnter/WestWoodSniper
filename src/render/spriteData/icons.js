const cache = new Map();
/** @returns {HTMLCanvasElement} */
export function icon(name, color, shade = '#3E8A3D', accent = '#FFB23A') {
  const key = name + color + shade + accent;
  let c = cache.get(key);
  if (c) return c;
  const g = ICONS[name];
  const p = new Pix(g[0].length, g.length);
  p.grid(g, { '#': color, '+': shade, '*': accent });
  c = p.toCanvas();
  cache.set(key, c);
  return c;
}
