const FONTS = {
  '5x7': { glyphs: G57, h: 7, space: 3, gap: 1, lineH: 9 },
  '3x5': { glyphs: G35, h: 5, space: 2, gap: 1, lineH: 7 },
};

/** Per (font, colour) glyph atlas cache */
const atlasCache = new Map();

function buildAtlas(fontName, color, bold) {
  const f = FONTS[fontName];
  const chars = Object.keys(f.glyphs);
  const cellW = 8, cellH = f.h;
  const c = makeCanvas(cellW * chars.length, cellH);
  const ctx = /** @type {CanvasRenderingContext2D} */ (c.getContext('2d'));
  ctx.fillStyle = color;
  const map = new Map();
  chars.forEach((ch, i) => {
    const rows = f.glyphs[ch];
    let w = 0;
    for (let y = 0; y < rows.length; y++) {
      const r = rows[y];
      w = Math.max(w, r.length);
      for (let x = 0; x < r.length; x++) if (r[x] === '#') {
        ctx.fillRect(i * cellW + x, y, 1, 1);
        // bold: thicken rightwards, but keep single-pixel counters open
        if (bold && r[x + 2] !== '#') ctx.fillRect(i * cellW + x + 1, y, 1, 1);
      }
    }
    map.set(ch, { sx: i * cellW, w: w + (bold ? 1 : 0) });
  });
  return { canvas: c, map, font: f };
}

function atlas(fontName, color, bold = false) {
  const key = fontName + color + (bold ? 'b' : '');
  let a = atlasCache.get(key);
  if (!a) { a = buildAtlas(fontName, color, bold); atlasCache.set(key, a); }
  return a;
}

function norm(ch) {
  if (ch >= 'a' && ch <= 'z') return ch.toUpperCase();
  if (ch === '…') return '.';
  if (ch === '—' || ch === '–') return '-';
  if (ch === '’' || ch === '‘') return "'";
  if (ch === '“' || ch === '”') return '"';
  return ch;
}

/**
 * Measure text width in px.
 * @param {string} text
 * @param {{font?: string, bold?: boolean, scale?: number}} [o]
 */
export function measureText(text, o = {}) {
  const fn = o.font || '5x7';
  const f = FONTS[fn];
  const a = atlas(fn, '#fff', o.bold);
  let w = 0, max = 0;
  for (const raw of text) {
    if (raw === '\n') { max = Math.max(max, w); w = 0; continue; }
    const ch = norm(raw);
    if (ch === ' ') { w += f.space + f.gap; continue; }
    const g = a.map.get(ch);
    w += (g ? g.w : 3) + f.gap;
  }
  max = Math.max(max, w);
  return Math.max(0, max - f.gap) * (o.scale || 1);
}

/**
 * Draw pixel text.
 * @param {CanvasRenderingContext2D} ctx
 * @param {string} text
 * @param {number} x
 * @param {number} y  top
 * @param {{color?: string, font?: string, align?: 'left'|'center'|'right', shadow?: string|null, bold?: boolean, scale?: number, maxW?: number}} [o]
 */
export function drawText(ctx, text, x, y, o = {}) {
  const fn = o.font || '5x7';
  const f = FONTS[fn];
  const color = o.color || '#7CFF7A';
  const s = o.scale || 1;
  const lines = String(text).split('\n');
  let yy = Math.round(y);
  for (const line of lines) {
    const w = measureText(line, o);
    let xx = Math.round(o.align === 'center' ? x - w / 2 : o.align === 'right' ? x - w : x);
    if (o.shadow) drawLine(ctx, line, xx + s, yy + s, fn, o.shadow, o.bold, s);
    drawLine(ctx, line, xx, yy, fn, color, o.bold, s);
    yy += f.lineH * s;
  }
}

function drawLine(ctx, line, x, y, fn, color, bold, s) {
  const a = atlas(fn, color, bold);
  const f = a.font;
  for (const raw of line) {
    const ch = norm(raw);
    if (ch === ' ') { x += (f.space + f.gap) * s; continue; }
    const g = a.map.get(ch);
    if (!g) { x += (3 + f.gap) * s; continue; }
    ctx.drawImage(a.canvas, g.sx, 0, g.w, f.h, x, y, g.w * s, f.h * s);
    x += (g.w + f.gap) * s;
  }
}

/** Word-wrap text to a pixel width. */
export function wrapText(text, maxW, o = {}) {
  const out = [];
  for (const para of String(text).split('\n')) {
    let cur = '';
    for (const word of para.split(' ')) {
      const t = cur ? cur + ' ' + word : word;
      if (measureText(t, o) > maxW && cur) { out.push(cur); cur = word; } else cur = t;
    }
    out.push(cur);
  }
  return out;
}

export function lineHeight(font = '5x7') { return FONTS[font].lineH; }
